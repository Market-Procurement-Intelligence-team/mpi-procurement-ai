/**
 * Printable documents for an order: the purchase order and each invoice.
 *
 * Opens a clean page in a new tab and starts the browser's print dialog,
 * where people can print it or choose "Save as PDF". Nothing is stored.
 */

import type { InvoiceSummary } from "../../services/data/money"
import type { OrderSummary } from "../../services/data/orders"
import type { QuoteLine } from "../../services/data/quotes"

const esc = (s: unknown) =>
  String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!)

const inr = (n: number, paise = false) =>
  `₹${Number(n || 0).toLocaleString("en-IN", { minimumFractionDigits: paise ? 2 : 0, maximumFractionDigits: 2 })}`

const date = (d: string | null | undefined) =>
  d ? new Date(d).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric" }) : "Not set"

const DUE: Record<string, string> = { on_order: "Before work starts", on_delivery: "On delivery", on_settlement: "When MPI settles" }

const STYLE = `
  *{box-sizing:border-box} body{font-family:Inter,system-ui,sans-serif;color:#15233d;margin:0;padding:40px;font-size:13px}
  header{display:flex;justify-content:space-between;align-items:flex-start;border-bottom:3px solid #f09a47;padding-bottom:16px;margin-bottom:20px}
  h1{font-size:22px;margin:0 0 4px} .muted{color:#5f6b7c} .brand{font-weight:800;font-size:20px;letter-spacing:-.02em}
  .grid{display:grid;grid-template-columns:1fr 1fr;gap:16px;margin-bottom:20px}
  .box{border:1px solid #cbd2dc;border-radius:8px;padding:12px} .box b{display:block;margin-bottom:4px}
  table{width:100%;border-collapse:collapse;margin-bottom:16px} th{background:#15233d;color:#fff;text-align:left;font-size:11px;text-transform:uppercase;letter-spacing:.05em}
  th,td{padding:8px 10px} td{border-bottom:1px solid #e8ecf3} .r{text-align:right}
  .total td{font-weight:800;font-size:15px;border-top:2px solid #15233d}
  footer{margin-top:28px;font-size:11px} @media print{body{padding:0}}
`

function open(title: string, body: string) {
  const w = window.open("", "_blank")
  if (!w) return false
  w.document.write(
    `<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title><style>${STYLE}</style></head><body>${body}` +
      `<footer class="muted">Generated by MPI. Payments in this demo are simulated: no real money moved.</footer>` +
      `<script>window.onload=function(){window.print()}</script></body></html>`,
  )
  w.document.close()
  return true
}

/** The purchase order. Returns false if the browser blocked the new tab. */
export function printPurchaseOrder(order: OrderSummary, lines: QuoteLine[], total: number | undefined): boolean {
  const rows = lines
    .map((l) => {
      const amt = Number(l.quantity) * Number(l.unit_price)
      return `<tr><td>${esc(l.description)}</td><td class="r">${Number(l.quantity).toLocaleString("en-IN")}</td><td class="r">${inr(Number(l.unit_price), true)}</td><td class="r">${Number(l.tax_rate)}%</td><td class="r">${inr(amt)}</td></tr>`
    })
    .join("")
  const sub = lines.reduce((n, l) => n + Number(l.quantity) * Number(l.unit_price), 0)
  return open(
    order.po_number,
    `<header><div><div class="brand">MPI</div><div class="muted">Purchase order</div></div>
      <div style="text-align:right"><h1>${esc(order.po_number)}</h1><div class="muted">Placed ${date(order.approved_at)}</div></div></header>
     <div class="grid">
      <div class="box"><b>Buyer</b>${esc(order.buyerName)}</div>
      <div class="box"><b>Supplier</b>${esc(order.supplierName)}</div>
      <div class="box"><b>For</b>${esc(order.requestTitle)}</div>
      <div class="box"><b>Expected delivery</b>${date(order.expected_delivery)}</div>
     </div>
     <table><thead><tr><th>Item</th><th class="r">Qty</th><th class="r">Price</th><th class="r">GST</th><th class="r">Amount</th></tr></thead>
      <tbody>${rows}<tr class="total"><td colspan="4">Items before GST</td><td class="r">${inr(sub)}</td></tr></tbody></table>
     ${total !== undefined ? `<p><b>Order total incl. GST:</b> ${inr(total)}</p>` : ""}
     <p class="muted">Both parties are verified by MPI. Names are shown as MPI aliases.</p>`,
  )
}

/** One invoice with its parts. Returns false if the browser blocked the new tab. */
export function printInvoice(order: OrderSummary, invoice: InvoiceSummary, label: string): boolean {
  const parts = (invoice.installments ?? [])
    .map((x) => `<tr><td>${esc(x.label || DUE[x.due] || x.due)}</td><td>${x.status === "paid" ? `Paid ${date(x.paid_at)}` : x.status === "waived" ? "Waived" : "Due"}</td><td class="r">${inr(x.amount)}</td></tr>`)
    .join("")
  return open(
    invoice.number,
    `<header><div><div class="brand">MPI</div><div class="muted">${esc(label)}</div></div>
      <div style="text-align:right"><h1>${esc(invoice.number)}</h1><div class="muted">Issued ${date(invoice.issued_at)}</div></div></header>
     <div class="grid">
      <div class="box"><b>Order</b>${esc(order.po_number)}<br>${esc(order.requestTitle)}</div>
      <div class="box"><b>Between</b>${esc(order.buyerName)}<br>${esc(order.supplierName)}</div>
     </div>
     <table><tbody>
      <tr><td>Amount before GST</td><td class="r">${inr(invoice.taxable)}</td></tr>
      <tr><td>GST</td><td class="r">${inr(invoice.gst)}</td></tr>
      <tr class="total"><td>Total</td><td class="r">${inr(invoice.total)}</td></tr>
     </tbody></table>
     ${parts ? `<table><thead><tr><th>Part</th><th>Status</th><th class="r">Amount</th></tr></thead><tbody>${parts}</tbody></table>` : ""}`,
  )
}
